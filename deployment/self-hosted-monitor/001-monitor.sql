CREATE TABLE IF NOT EXISTS public.key_restriction_config (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(), api_key_id bigint NOT NULL UNIQUE,
  team_id uuid NOT NULL,
  allowed_formats jsonb NOT NULL DEFAULT '[]'::jsonb,
  allowed_endpoints jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (api_key_id, team_id) REFERENCES public.api_keys(id, team_id) ON DELETE CASCADE,
