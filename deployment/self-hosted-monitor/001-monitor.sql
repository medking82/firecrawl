-- Local policy/ledger tables deliberately separate from upstream Drizzle tables.
-- JS currently replaces RPC rate/concurrency limits with DEFAULT_TEAM_LIMITS when
-- Autumn is absent (2 / 1 / false). Changing these SQL values alone does not
-- change those effective HTTP limits. No external billing integration is supplied.
CREATE TABLE IF NOT EXISTS public.self_hosted_team_policy (
  team_id uuid PRIMARY KEY REFERENCES public.teams(id),
  flags jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(flags) = 'object'),
  concurrency_limit integer NOT NULL DEFAULT 2 CHECK (concurrency_limit > 0),
  rate_limit_multiplier integer NOT NULL DEFAULT 1 CHECK (rate_limit_multiplier > 0),
  is_paid_plan boolean NOT NULL DEFAULT false
);
CREATE TABLE IF NOT EXISTS public.self_hosted_usage_ledger (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  team_id uuid NOT NULL REFERENCES public.teams(id),
  api_key_id bigint REFERENCES public.api_keys(id) ON DELETE SET NULL,
  credits bigint NOT NULL CHECK (credits >= 0), is_extract boolean NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS self_hosted_usage_ledger_team_idx ON public.self_hosted_usage_ledger(team_id, created_at);

CREATE OR REPLACE FUNCTION public.auth_chunk_2(input_key text, input_credential_purpose text DEFAULT 'general')
RETURNS TABLE (api_key text, api_key_id bigint, team_id uuid, org_id uuid,
  flags jsonb, is_banned boolean, concurrency_limit integer, rate_limit_multiplier integer, is_paid_plan boolean)
LANGUAGE sql STABLE SET search_path = pg_catalog, public AS $$
  SELECT k.key::text, k.id, t.id, t.org_id, coalesce(p.flags, '{}'::jsonb),
    coalesce(t.banned, false), coalesce(p.concurrency_limit, 2),
    coalesce(p.rate_limit_multiplier, 1), coalesce(p.is_paid_plan, false)
  FROM public.api_keys k JOIN public.teams t ON t.id = k.team_id
  LEFT JOIN public.self_hosted_team_policy p ON p.team_id = t.id
  WHERE k.key::text = lower(input_key) AND input_credential_purpose = 'general'
    AND NOT coalesce(k.agent_provisioned, false)
$$;
CREATE OR REPLACE FUNCTION public.auth_chunk_2_from_team(input_team text)
RETURNS TABLE (api_key text, api_key_id bigint, team_id uuid, org_id uuid,
  flags jsonb, is_banned boolean, concurrency_limit integer, rate_limit_multiplier integer, is_paid_plan boolean)
LANGUAGE sql STABLE SET search_path = pg_catalog, public AS $$
  SELECT NULL::text, NULL::bigint, t.id, t.org_id, coalesce(p.flags, '{}'::jsonb),
    coalesce(t.banned, false), coalesce(p.concurrency_limit, 2),
    coalesce(p.rate_limit_multiplier, 1), coalesce(p.is_paid_plan, false)
  FROM public.teams t LEFT JOIN public.self_hosted_team_policy p ON p.team_id = t.id
  WHERE t.id::text = lower(input_team)
$$;

-- Matches db/rpc.ts's named arguments. Records actual usage, not prepaid Cloud
-- credits; no budget enforcement or retry deduplication is implied by this RPC
-- (its signature has no charge/job id). One durable row per successful call.
CREATE OR REPLACE FUNCTION public.bill_team_7(_team_id text, sub_id text, credits integer,
  i_api_key_id bigint, is_extract_param boolean)
RETURNS TABLE (api_key text) LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
DECLARE v_team uuid; v_key text;
BEGIN
  IF credits IS NULL OR credits < 0 OR is_extract_param IS NULL OR sub_id IS NOT NULL THEN
    RAISE EXCEPTION 'Invalid local usage charge or unsupported subscription' USING ERRCODE = '22023';
  END IF;
  SELECT t.id INTO v_team FROM public.teams t
    WHERE t.id::text = lower(_team_id) AND NOT coalesce(t.banned, false) FOR SHARE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Unknown or banned local team' USING ERRCODE = '23503'; END IF;
  IF i_api_key_id IS NOT NULL THEN
    SELECT k.key::text INTO v_key FROM public.api_keys k WHERE k.id = i_api_key_id AND k.team_id = v_team FOR SHARE;
    IF NOT FOUND THEN RAISE EXCEPTION 'API key does not belong to local team' USING ERRCODE = '23503'; END IF;
  END IF;
  INSERT INTO public.self_hosted_usage_ledger(team_id, api_key_id, credits, is_extract)
    VALUES (v_team, i_api_key_id, credits, is_extract_param);
  RETURN QUERY SELECT v_key;
END $$;

-- The scheduler owns cron/timezone calculation and overlap/stale-check handling.
-- Claim must NOT advance next_run_at or exclude current_check_id: scheduler.ts
-- creates skipped_overlap checks or reconciles the current check itself.
-- worker_id is a diagnostic input only: upstream has no lock-owner column or
-- fencing token. Lease expiry allows redelivery, not exactly-once execution.
CREATE OR REPLACE FUNCTION public.monitoring_claim_due_monitors(
  p_worker_id text, p_limit integer, p_lease_seconds integer)
RETURNS SETOF public.monitors LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
DECLARE v_now timestamptz := statement_timestamp();
BEGIN
  IF p_worker_id IS NULL OR btrim(p_worker_id) = '' OR p_limit IS NULL OR p_limit < 1
     OR p_lease_seconds IS NULL OR p_lease_seconds < 1 THEN
    RAISE EXCEPTION 'worker id, positive limit and lease seconds required' USING ERRCODE = '22023';
  END IF;
  RETURN QUERY
  WITH due AS (
    SELECT m.id FROM public.monitors m
    WHERE m.status = 'active' AND m.deleted_at IS NULL
      AND m.next_run_at <= v_now AND (m.locked_until IS NULL OR m.locked_until <= v_now)
    ORDER BY m.next_run_at, m.id
    LIMIT p_limit FOR UPDATE OF m SKIP LOCKED
  )
  UPDATE public.monitors m SET locked_at = v_now,
    locked_until = v_now + make_interval(secs => p_lease_seconds), updated_at = v_now
  FROM due WHERE m.id = due.id RETURNING m.*;
END $$;

-- Function privileges are intended for the isolated API DB role, not PUBLIC.
-- Deployer grants EXECUTE explicitly if API runs as a different role from owner.
REVOKE ALL ON FUNCTION public.auth_chunk_2(text, text) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.auth_chunk_2_from_team(text) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.bill_team_7(text, text, integer, bigint, boolean) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.monitoring_claim_due_monitors(text, integer, integer) FROM PUBLIC;
COMMIT;
