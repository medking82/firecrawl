-- Firecrawl v2.11.621 (33f295dc), isolated self-hosted monitor database only.
-- Apply with psql -X -v ON_ERROR_STOP=1 -f 001-monitor.sql to a NEW database.
-- No tenant or API secret is seeded here. API keys are UUIDs, not fc- prefixed.
-- Local compatibility deviation: teams.org_id permits NULL (upstream NOT NULL)
-- so the existing monitor runner skips external credit locks/billing providers.
-- This is a bounded bootstrap, not an upgrade migration or a Cloud schema copy.
-- Auth key revocation = DELETE api_keys + invalidate the API's Redis auth cache.
-- Only general credentials are supported; hosted MCP OAuth fails closed.
BEGIN;
CREATE SCHEMA IF NOT EXISTS extensions;
CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;
-- Fail clearly if an existing database installed pgcrypto into another schema.
DO $$ BEGIN
  IF to_regprocedure('extensions.gen_random_bytes(integer)') IS NULL THEN
    RAISE EXCEPTION 'Expected pgcrypto in extensions; use a new isolated database';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.teams (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  created_at timestamptz DEFAULT now(), name text, banned boolean DEFAULT false,
  idmux_expires_at timestamptz, updated_at timestamptz DEFAULT now(),
  hmac_secret text NOT NULL DEFAULT encode(extensions.gen_random_bytes(32), 'hex'::text),
  referrer_integration varchar, allocated_concurrent_browsers integer, org_id uuid
);
CREATE TABLE IF NOT EXISTS public.api_keys (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz DEFAULT now(), key uuid DEFAULT gen_random_uuid() UNIQUE,
  name text, team_id uuid REFERENCES public.teams(id), owner_id uuid,
  agent_provisioned boolean DEFAULT false, concurrency integer,
  CONSTRAINT api_keys_id_team_id_key UNIQUE (id, team_id),
  CHECK (concurrency IS NULL OR concurrency > 0)
);
CREATE INDEX IF NOT EXISTS api_keys_team_idx ON public.api_keys(team_id);
-- initializeBlocklist runs during authenticated worker startup. Keep the real
-- store and hit logging available; do not disable the blocklist initialization.
