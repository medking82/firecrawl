-- Additive browser-only compatibility schema for the v2.11.626 auth lookup.
-- Column types, nullability and defaults follow apps/api/src/db/schema/public.ts.
BEGIN;
SET LOCAL lock_timeout = '3s';
CREATE TABLE IF NOT EXISTS public.agent_sponsors (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  email text NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  verification_deadline timestamptz NOT NULL,
  agent_name text NOT NULL,
  sandboxed_team_id uuid,
  api_key_id bigint,
  requesting_ip text,
  tos_version text,
  tos_hash text,
  verification_token text NOT NULL,
  created_at timestamptz DEFAULT now(),
  verified_at timestamptz,
  updated_at timestamptz DEFAULT now()
);
-- Existing incompatible tables fail closed instead of being silently accepted.
DO $$
DECLARE bad integer;
BEGIN
  SELECT count(*) INTO bad
  FROM (VALUES
    ('id','bigint','NO'), ('email','text','NO'), ('status','text','NO'),
    ('verification_deadline','timestamp with time zone','NO'), ('agent_name','text','NO'),
    ('sandboxed_team_id','uuid','YES'), ('api_key_id','bigint','YES'),
    ('requesting_ip','text','YES'), ('tos_version','text','YES'), ('tos_hash','text','YES'),
    ('verification_token','text','NO'), ('created_at','timestamp with time zone','YES'),
    ('verified_at','timestamp with time zone','YES'), ('updated_at','timestamp with time zone','YES')
  ) AS expected(name, typ, nullable)
  LEFT JOIN information_schema.columns c ON c.table_schema='public'
    AND c.table_name='agent_sponsors' AND c.column_name=expected.name
  WHERE c.column_name IS NULL OR c.data_type <> expected.typ OR c.is_nullable <> expected.nullable;
  IF bad <> 0 OR NOT EXISTS (
    SELECT 1 FROM information_schema.columns WHERE table_schema='public'
      AND table_name='agent_sponsors' AND column_name='id'
      AND is_identity='YES' AND identity_generation='BY DEFAULT'
  ) THEN
    RAISE EXCEPTION 'existing agent_sponsors schema is incompatible';
  END IF;
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema='public' AND table_name='agent_sponsors'
      AND ((column_name='status' AND column_default IS DISTINCT FROM '''pending''::text')
        OR (column_name IN ('created_at','updated_at') AND column_default IS DISTINCT FROM 'now()')
        OR (column_name IN ('id','email','verification_deadline','agent_name','sandboxed_team_id',
                            'api_key_id','requesting_ip','tos_version','tos_hash','verification_token','verified_at')
            AND column_default IS NOT NULL))
  ) THEN
    RAISE EXCEPTION 'existing agent_sponsors defaults are incompatible';
  END IF;
  IF EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid='public.agent_sponsors'::regclass AND contype IN ('c','f','p','u','x')
  ) THEN
    RAISE EXCEPTION 'existing agent_sponsors constraints are incompatible';
  END IF;
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema='public' AND table_name='agent_sponsors'
      AND column_name NOT IN ('id','email','status','verification_deadline','agent_name',
                              'sandboxed_team_id','api_key_id','requesting_ip','tos_version','tos_hash',
                              'verification_token','created_at','verified_at','updated_at')
      AND is_nullable='NO' AND column_default IS NULL AND is_identity='NO'
  ) THEN
    RAISE EXCEPTION 'existing agent_sponsors has required extra columns';
  END IF;
END $$;
COMMIT;
