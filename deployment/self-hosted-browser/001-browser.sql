-- New isolated browser database only. Authentication/RPC bootstrap is shared with monitor.
BEGIN;
CREATE TABLE IF NOT EXISTS public.browser_sessions (
 id uuid PRIMARY KEY, zero_data_retention boolean NOT NULL DEFAULT false,
 team_id text NOT NULL, request_id uuid, should_bill boolean NOT NULL DEFAULT true,
 browser_id text NOT NULL, workspace_id text NOT NULL, context_id text NOT NULL,
 cdp_url text NOT NULL, cdp_path text NOT NULL, stream_web_view boolean NOT NULL DEFAULT false,
 status text NOT NULL DEFAULT 'active', ttl_total integer NOT NULL,
 ttl_without_activity integer, created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(), deleted_at timestamptz,
 credits_used integer, cdp_interactive_path text, scrape_id uuid, profile_name text
);
CREATE INDEX IF NOT EXISTS browser_sessions_team_status ON public.browser_sessions(team_id,status);
CREATE INDEX IF NOT EXISTS browser_sessions_scrape ON public.browser_sessions(scrape_id);
CREATE TABLE IF NOT EXISTS public.browser_session_activities (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, team_id text NOT NULL,
 session_id text NOT NULL, language text NOT NULL, timeout integer NOT NULL,
 exit_code integer, killed boolean NOT NULL DEFAULT false,
 created_at timestamptz NOT NULL DEFAULT now(), source text DEFAULT 'browser'
);
CREATE TABLE IF NOT EXISTS public.browser_profiles (
 team_id uuid NOT NULL, name text NOT NULL, created_at timestamptz NOT NULL DEFAULT now(),
 saved_at timestamptz NOT NULL, size_bytes bigint, PRIMARY KEY(team_id,name)
);
COMMIT;
